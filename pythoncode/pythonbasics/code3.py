# python input and output

# python input function : input()

name = input("Enter your name: ")  

#python output function : print()
print("Hello, " + name + "! Welcome to Python programming.")
# using f-string for formatting
print(f"Hello, {name}! Welcome to Python programming.") 
# using format method for formatting 
print("Hello, {}! Welcome to Python programming.".format(name)) 
# using old-style string formatting
print("Hello, %s! Welcome to Python programming." % name)  